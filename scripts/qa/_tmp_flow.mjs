import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 844, height: 390 } });
p.on('pageerror', e => console.log('pageerror:', e.message));
p.on('console', m => { if (m.type() === 'error') console.log('console:', m.text().slice(0, 200)); });
await p.goto('http://127.0.0.1:5173/');
await p.waitForFunction(() => window.__ckStarted === true, null, { timeout: 120000 });
const claim = await p.$('[data-a=claim]'); if (claim) await claim.click();
await p.evaluate(() => { window.cageKings.qaSpeed(30); window.cageKings.qaAutoplay(true); });
await p.evaluate(() => window.cageKings.qaNav({ s: 'career', div: 'mLight' }));
await p.waitForTimeout(2500);
await p.click('[data-a=fight]');
const t0 = Date.now();
await p.waitForSelector('.result-card', { timeout: 300000 });
console.log('fight took', Math.round((Date.now() - t0) / 1000), 's real');
await p.waitForTimeout(500);
await p.screenshot({ path: '/tmp/q/flow_result.png' });
await p.click('[data-a=next]');
await p.waitForTimeout(6000);
await p.screenshot({ path: '/tmp/q/flow_after.png' });
const st = await p.evaluate(() => { const s = window.cageKings.debugState(); return { route: s.route, career: s.save.progress.career.div.mLight, cash: s.save.cash, fights: s.save.fights }; });
console.log(JSON.stringify(st));
await b.close();
